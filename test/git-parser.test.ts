import test from "node:test";
import assert from "node:assert/strict";
import {
  detectActorKind,
  extractCoAuthors,
  extractIssueRefs,
  isCriticalPathFile,
  parseGitLogOutput,
} from "../src/core/git-parser.ts";

test("detectActorKind correctly identifies bots, agents and humans", () => {
  assert.equal(detectActorKind("Manoj Rollo", "fbxmano@gmail.com", "feat: initial commit"), "human");
  assert.equal(detectActorKind("copilot[bot]", "copilot@github.com", "refactor: simplify loops"), "agent");
  assert.equal(detectActorKind("Claude Assistant", "claude@anthropic.com", "test: add edge cases"), "agent");
  assert.equal(detectActorKind("GitHub Actions", "actions@github.com", "chore: release"), "agent");
});

test("isCriticalPathFile correctly flags sensitive repository files", () => {
  assert.equal(isCriticalPathFile(".github/workflows/ci.yml"), true);
  assert.equal(isCriticalPathFile("package.json"), true);
  assert.equal(isCriticalPathFile("tsconfig.build.json"), true);
  assert.equal(isCriticalPathFile("src/auth/token.ts"), true);
  assert.equal(isCriticalPathFile("src/core/reconciler.ts"), false);
  assert.equal(isCriticalPathFile("README.md"), false);
});

test("extractIssueRefs identifies issue identifiers from commit messages", () => {
  const text = "feat: implement ledger parser (#42, fixes #108 and GH-9)";
  const refs = extractIssueRefs(text);
  assert.deepEqual(refs, [9, 42, 108]);
});

test("extractCoAuthors extracts Co-authored-by, Reviewed-by and Signed-off-by trailers", () => {
  const body = "Initial work\n\nCo-authored-by: Alice <alice@example.com>\nReviewed-by: Lead Maintainer <lead@example.com>\nSigned-off-by: Bob <bob@example.com>";
  const trailers = extractCoAuthors(body);
  assert.deepEqual(trailers, [
    "Alice <alice@example.com>",
    "Lead Maintainer <lead@example.com>",
    "Bob <bob@example.com>",
  ]);
});

test("parseGitLogOutput parses git log entries with numstat insertions and deletions", () => {
  const rawLog = `c0ffee1234567890abcdef1234567890abcdef12
Manoj Rollo
fbxmano@gmail.com
2026-11-06T12:00:00Z
feat: add work ledger core (#1)
Implements factual evidence reconciliation.
--FILES--
24	2	src/core/reconciler.ts
5	0	src/core/types.ts
---DEVPILOT-COMMIT-END---
deadbeef1234567890abcdef1234567890abcdef
agent-bot
agent@bot.local
2026-11-06T12:30:00Z
fix: touch sensitive github workflow
Generated by LLM agent.
--FILES--
10	1	.github/workflows/ci.yml
`;

  const commits = parseGitLogOutput(rawLog);
  assert.equal(commits.length, 2);

  assert.equal(commits[0]?.shortSha, "c0ffee1");
  assert.equal(commits[0]?.actorKind, "human");
  assert.deepEqual(commits[0]?.issueRefs, [1]);
  assert.equal(commits[0]?.insertions, 29);
  assert.equal(commits[0]?.deletions, 2);
  assert.equal(commits[0]?.isCriticalPath, false);

  assert.equal(commits[1]?.shortSha, "deadbee");
  assert.equal(commits[1]?.actorKind, "agent");
  assert.equal(commits[1]?.insertions, 10);
  assert.equal(commits[1]?.deletions, 1);
  assert.equal(commits[1]?.isCriticalPath, true);
});
